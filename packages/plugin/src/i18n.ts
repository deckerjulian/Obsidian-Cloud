function detectLanguage(): string {
  try {
    if (typeof getLanguage === 'function') return getLanguage();
  } catch {
    /* older Obsidian */
  }
  return window.localStorage.getItem('language') ?? 'en';
}

export const lang: 'de' | 'en' = detectLanguage().toLowerCase().startsWith('de') ? 'de' : 'en';
const dict: Record<Key, string> = lang === 'de' ? de : en;

export function t(key: Key, vars?: Record<string, string | number>): string {
  const s = dict[key] ?? en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

/** "just now", "5 minutes ago", "yesterday", … in the UI language. */
export function relativeTime(ms: number, now = Date.now()): string {
  const s = Math.round((ms - now) / 1000);
  if (Math.abs(s) < 45) return t('time.justNow');
  const rtf = new Intl.RelativeTimeFormat(lang, { numeric: 'auto' });
  const m = Math.round(s / 60);
  if (Math.abs(m) < 60) return rtf.format(m, 'minute');
  const h = Math.round(m / 60);
  if (Math.abs(h) < 24) return rtf.format(h, 'hour');
  return rtf.format(Math.round(h / 24), 'day');
}
