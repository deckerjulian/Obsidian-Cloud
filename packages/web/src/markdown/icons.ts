const custom = new Map<string, string>();

/** Register a custom icon (Obsidian's `addIcon`, 100×100 viewBox). */
export function addIcon(id: string, svgContent: string): void {
  custom.set(id, svgContent);
}

export function iconSvg(name: string, size = 16): string | null {
  const id = name.replace(/^lucide-/, '');
  const c = custom.get(name) ?? custom.get(id);
  if (c) {
    return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 100 100" fill="currentColor" class="svg-icon ${name}">${c}</svg>`;
  }
  const inner = ICONS[id] ?? ICONS[ALIASES[id] ?? ''];
  if (!inner) return null;
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" ` +
    `stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" class="svg-icon lucide-${id}">${inner}</svg>`
  );
}

/** Obsidian's `setIcon(el, id)`: replace the element's children with the icon. */
export function setIcon(el: HTMLElement, name: string, size = 16): void {
  el.innerHTML = iconSvg(name, size) ?? '';
}

export function getIconIds(): string[] {
  return [...Object.keys(ICONS).map((k) => `lucide-${k}`), ...custom.keys()];
}

